BEGIN;
-- Conserva los IDs existentes y permite que PostgreSQL asigne los nuevos.
DO $$
DECLARE maximum_id bigint;
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_attribute
    WHERE attrelid = 'public.productos'::regclass AND attname = 'id' AND attidentity = ''
  ) THEN
    ALTER TABLE public.productos ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    SELECT max(id) INTO maximum_id FROM public.productos;
    PERFORM setval(pg_get_serial_sequence('public.productos', 'id'), COALESCE(maximum_id, 1), maximum_id IS NOT NULL);
  END IF;
  EXECUTE format('GRANT USAGE ON SEQUENCE %s TO authenticated', pg_get_serial_sequence('public.productos', 'id'));
END;
$$;
COMMIT;
